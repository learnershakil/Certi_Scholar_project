import { VerificationProviderType, VerificationStatus } from '@repo/contracts';
import { IVerificationProvider, VerificationContext, VerificationExecutionResult } from '../types';
import { config } from '../../../config/env';

export class SimulatedAdapter implements IVerificationProvider {
  readonly providerType = VerificationProviderType.SIMULATED;

  isAvailable(): boolean {
    return !config.isProd && config.enableSimulatedProvider;
  }

  async verify(context: VerificationContext): Promise<VerificationExecutionResult> {
    if (config.isProd) {
      throw new Error(
        '[FATAL SECURITY CONFIG] Simulated verification provider is strictly prohibited and hard-blocked in production environment.'
      );
    }
    if (!config.enableSimulatedProvider) {
      throw new Error(
        'Simulated verification provider is not enabled. Set ENABLE_SIMULATED_PROVIDER=true only for local testing or demos.'
      );
    }

    const scenario = context.simulatedScenario || 'MATCH';

    if (scenario === 'MISMATCH') {
      return {
        provider: this.providerType,
        status: VerificationStatus.SIMULATED_NOT_MATCHED,
        isAuthenticityVerified: false,
        retrievalOnly: false,
        isSimulated: true,
        evidenceReference: 'SIMULATED-EVIDENCE-MISMATCH',
        notes:
          'SIMULATED DEMO ONLY: Simulated issuer returned mismatch. This mock response does NOT represent a real verification.',
      };
    }

    if (scenario === 'NOT_FOUND') {
      return {
        provider: this.providerType,
        status: VerificationStatus.NOT_FOUND,
        isAuthenticityVerified: false,
        retrievalOnly: false,
        isSimulated: true,
        notes:
          'SIMULATED DEMO ONLY: Simulated issuer returned record not found. This mock response does NOT represent a real verification.',
      };
    }

    if (scenario === 'UNAVAILABLE') {
      return {
        provider: this.providerType,
        status: VerificationStatus.UNAVAILABLE,
        isAuthenticityVerified: false,
        retrievalOnly: false,
        isSimulated: true,
        notes:
          'SIMULATED DEMO ONLY: Simulated provider mock outage. This mock response does NOT represent a real verification.',
      };
    }

    return {
      provider: this.providerType,
      status: VerificationStatus.SIMULATED_MATCH,
      isAuthenticityVerified: false, // Never authentic!
      retrievalOnly: false,
      isSimulated: true,
      evidenceReference: 'SIMULATED-EVIDENCE-MATCH',
      issuerMetadata: {
        simulatedAt: new Date().toISOString(),
        disclaimer: 'This data was generated by a local test fixture and does not constitute issuer authenticity.',
      },
      notes:
        'SIMULATED DEMO ONLY: Mock provider returned simulated match. This does NOT establish genuine issuer authenticity.',
    };
  }
}

export const simulatedAdapter = new SimulatedAdapter();

